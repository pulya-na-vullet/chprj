# T-0128 (спека E19 §7): подписи профиля для профильного блока промпта.
# Ключи — перечисления contracts/auth.py; неизвестные значения молча
# пропускаются (профиль пишется только валидированным PATCH /profile).
_USAGE_LABELS = {
    "personal": "использует сервис для себя",
    "business": "использует сервис для бизнеса",
}
_ROLE_LABELS = {
    "lawyer": "юрист",
    "accountant": "бухгалтер",
    "manager": "руководитель",
    "other": "другая роль",
}
_TASK_LABELS = {
    "law_questions": "вопросы по законодательству",
    "contract_review": "проверка договоров",
    "drafting": "составление документов",
    "files": "работа со своими файлами",
}


def build_profile_note(user: UserRow) -> str | None:
    """Короткий профильный блок для системного промпта (T-0128).

    Только реально заполненные поля; пустой профиль — None (промпт не
    трогаем). Блок влияет на тон и примеры и явно объявляет, что правила
    ответов не меняет — правило «только из результатов поиска» плюс
    цитирование остаются в базовом промпте. Роль упоминается только в
    ветке бизнеса — та же логика, что в UI онбординга.
    """
    lines: list[str] = []
    name = " ".join(
        part for part in ((user.first_name or "").strip(), (user.last_name or "").strip()) if part
    )
    if name:
        lines.append(f"Имя: {name}. Можно обращаться по имени.")
    usage = _USAGE_LABELS.get(user.usage_kind or "")
    if usage:
        lines.append(f"Формат использования: {usage}.")
    if user.usage_kind == "business":
        role_label = _ROLE_LABELS.get(user.role or "")
        if role_label:
            lines.append(f"Кто по работе: {role_label}.")
    task_labels = [_TASK_LABELS[key] for key in (user.tasks or []) if key in _TASK_LABELS]
    if task_labels:
        lines.append("Чаще всего нужно: " + ", ".join(task_labels) + ".")
    if not lines:
        return None
    body = "\n".join(f"- {line}" for line in lines)
    return f"О пользователе (влияет на тон и примеры, правила ответов не меняет):\n{body}"


